    private void btnEnviarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEnviarActionPerformed
    String nombre = txtNombre.getText().trim();
    String correo = txtCorreo.getText().trim();
    String telefono = txtAsunto.getText().trim();
    String descripcion = txtComentarios.getText().trim();
    String horasTexto = txtHoras.getText().trim();

    String mensaje = "";

    // Si hay valor en el campo de horas
    if (!horasTexto.isEmpty()) {
        try {
            int horas = Integer.parseInt(horasTexto);
            int costo = horas * 200;
            mensaje += "Presupuesto estimado: $" + costo;
        } catch (NumberFormatException e) {
            mensaje += "Horas de uso inválidas. No se pudo calcular el presupuesto.";
        }
    }

    // Mostrar mensaje en el JLabel
    jLabel16.setText(mensaje);
    }//GEN-LAST:event_btnEnviarActionPerformed

