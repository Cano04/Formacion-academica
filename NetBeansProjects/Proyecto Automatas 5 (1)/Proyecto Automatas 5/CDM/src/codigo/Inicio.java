 private void analizarDeclaracionVariable(String[] tokens, int linea, List<String> errores, 
                                         Set<String> variablesDeclaradas, StringBuilder resultado) {
    if (tokens.length < 2) {
        String errorMsg = "Falta identificador en declaración de variable. Ejemplo: 'Vill MiVariable'";
        errores.add(linea + "| |" + errorMsg);
        resultado.append("Línea " + linea + ": " + errorMsg + "\n");
    } else if (tokens.length > 2) {
        String errorMsg = "Sobran elementos en declaración de variable. Solo se espera tipo e identificador, por ejemplo, 'Vill MiVariable'";
        errores.add(linea + "|" + String.join(" ", tokens) + "|" + errorMsg);
        resultado.append("Línea " + linea + ": " + errorMsg + "\n");
    } else {
        String tipo = tokens[0];
        String variable = tokens[1];
        if (!Arrays.asList("Vill", "Con", "Nad", "Gen").contains(tipo)) {
            String errorMsg = "Tipo de variable inválido: '" + tipo + "'. Se esperaba Vill, Con, Nad o Gen, con la primera letra en mayúscula";
            errores.add(linea + "|" + tipo + "|" + errorMsg);
            resultado.append("Línea " + linea + ": " + errorMsg + "\n");
        } else if (!esIdentificadorNuevo(variable)) {
            String errorMsg = "Identificador inválido: '" + variable + "'. Debe comenzar con mayúscula y contener solo letras y números, por ejemplo, 'MiVariable'";
            errores.add(linea + "|" + variable + "|" + errorMsg);
            resultado.append("Línea " + linea + ": " + errorMsg + "\n");
        } else if (variablesDeclaradas.contains(variable)) {
            String errorMsg = "Variable ya declarada anteriormente: '" + variable + "'. Use un nombre diferente";
            errores.add(linea + "|" + variable + "|" + errorMsg);
            resultado.append("Línea " + linea + ": " + errorMsg + "\n");
        } else {
            variablesDeclaradas.add(variable);
        }
    }
}
private void analizarAsignacion(String linea, int numeroLinea, List<String> errores, 
                                   Set<String> variablesDeclaradas, StringBuilder resultado) {
        int igualIndex = linea.indexOf('=');
        if (igualIndex == -1) {
            String errorMsg = "Falta '=' en la asignación. Ejemplo: 'X = 5'";
            errores.add(numeroLinea + "| |" + errorMsg);
            resultado.append("Línea " + numeroLinea + ": " + errorMsg + "\n");
            return;
        }
        String varParte = linea.substring(0, igualIndex).trim();
        String[] varTokens = varParte.split("\\s+");
        if (varTokens.length != 1) {
            String errorMsg = "Se esperaba un solo identificador en el lado izquierdo de la asignación, por ejemplo, 'X = 5'";
            errores.add(numeroLinea + "|" + varParte + "|" + errorMsg);
            resultado.append("Línea " + numeroLinea + ": " + errorMsg + "\n");
            return;
        }
        String variable = varTokens[0];
        if (!esIdentificadorNuevo(variable)) {
            String errorMsg = "Identificador inválido: '" + variable + "'. Debe comenzar con mayúscula y contener solo letras y números, por ejemplo, 'X'";
            errores.add(numeroLinea + "|" + variable + "|" + errorMsg);
            resultado.append("Línea " + numeroLinea + ": " + errorMsg + "\n");
            return;
        }
        if (!variablesDeclaradas.contains(variable)) {
            String errorMsg = "Variable no declarada: '" + variable + "'. Debe declararse primero con Vill, Con, Nad o Gen, por ejemplo, 'Vill X'";
            errores.add(numeroLinea + "|" + variable + "|" + errorMsg);
            resultado.append("Línea " + numeroLinea + ": " + errorMsg + "\n");
            return;
        }
        String exprParte = linea.substring(igualIndex + 1).trim();
        String errorExpr = validarExpresion(exprParte);
        if (errorExpr != null) {
            errores.add(numeroLinea + "|" + exprParte + "|" + errorExpr);
            resultado.append("Línea " + numeroLinea + ": " + errorExpr + "\n");
        }
    }

 private String validarExpresion(String expr) {
        String[] tokens = tokenizarLinea(expr);
        if (tokens.length == 0) {
            return "Expresión vacía. Se esperaba un número, identificador, 'Nad' o 'Gen', por ejemplo, '5' o 'X'";
        }
        boolean expectingTerm = true;
        for (int i = 0; i < tokens.length; i++) {
            String token = tokens[i];
            if (expectingTerm) {
                if (!esTerminoNuevo(token)) {
                    return "Se esperaba un término en la posición " + (i + 1) + ", pero se encontró '" + token + "'. Use un número, identificador, 'Nad' o 'Gen'";
                }
                expectingTerm = false;
            } else {
                if (!esOperadorNuevo(token)) {
                    return "Se esperaba un operador (+, -, *, /) en la posición " + (i + 1) + ", pero se encontró '" + token + "'";
                }
                expectingTerm = true;
            }
        }
        if (expectingTerm) {
            return "La expresión termina con un operador, se esperaba un término como un número o identificador";
        }
        return null;
    }
