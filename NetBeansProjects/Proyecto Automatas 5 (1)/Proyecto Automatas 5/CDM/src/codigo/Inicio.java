public boolean validarEstructuraBasica(String contenido) {
    try {
        Lexer lexer = new Lexer(new StringReader(contenido));
        Tokens token;
        boolean tieneInicio = false;
        boolean tieneFinal = false;
        
        while ((token = lexer.yylex()) != null && token != Tokens.EOF) {
            if (token == Tokens.DelimitadorPrincipal) {
                tieneInicio = true;
            } else if (token == Tokens.DelimitadorFinal) {
                tieneFinal = true;
            }
        }
        
        return tieneInicio && tieneFinal;
        
    } catch (Exception e) {
        return false;
    }
}
public java.util.Set<String> obtenerIdentificadores(String contenido) {
    java.util.Set<String> identificadores = new java.util.HashSet<>();
    
    try {
        Lexer lexer = new Lexer(new StringReader(contenido));
        Tokens token;
        
        while ((token = lexer.yylex()) != null && token != Tokens.EOF) {
            if (token == Tokens.Identificador && lexer.lexeme != null) {
                identificadores.add(lexer.lexeme);
            }
        }
        
    } catch (Exception e) {
        e.printStackTrace();
    }
    
    return identificadores;
}
