private boolean esExpresionValida(String expresion) {
    if (expresion == null || expresion.trim().isEmpty()) return false;
    
    String[] tokens = tokenizarLinea(expresion);
    if (tokens.length == 0) return false;
    
    // Expresión simple: un solo término
    if (tokens.length == 1) {
        return esTerminoValido(tokens[0]);
    }
    
    // Expresión compuesta: término operador término [operador término...]
    boolean esperandoTermino = true;
    
    for (String token : tokens) {
        if (esperandoTermino) {
            if (!esTerminoValido(token)) return false;
            esperandoTermino = false;
        } else {
            if (!esOperadorValido(token)) return false;
            esperandoTermino = true;
        }
    }
    
    return !esperandoTermino; // Debe terminar con término
}

private boolean esTerminoValido(String token) {
    return token.matches("\\d+(\\.\\d+)?") || // Número
           esIdentificadorValido(token) ||     // Identificador
           token.equals("Nad") ||              // Constante null
           token.equals("Gen") ||              // Constante genérica
           token.equals("Verdadero") ||        // Booleano true
           token.equals("Falso");              // Booleano false
}

private boolean esOperadorValido(String token) {
    return token.matches("[+\\-*/]") ||       // Aritméticos
           token.matches("(==|!=|<=|>=|<|>)") || // Relacionales
           token.equals("&&") ||              // AND lógico
           token.equals("||");                // OR lógico
}

