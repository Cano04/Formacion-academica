private void analizarSentencia(String linea, int numeroLinea, List<String> errores, 
                               Set<String> variablesDeclaradas, List<String> funcionesDeclaradas,
                               StringBuilder resultado) {
    String[] tokens = tokenizarLinea(linea);
    if (tokens.length == 0) return;
    
    String primerToken = tokens[0];
    
    // Verificar palabras reservadas en minúsculas o con formato incorrecto
    Map<String, String> palabrasReservadasCaseSensitive = new HashMap<>();
    palabrasReservadasCaseSensitive.put("vill", "Vill");
    palabrasReservadasCaseSensitive.put("con", "Con");
    palabrasReservadasCaseSensitive.put("nad", "Nad");
    palabrasReservadasCaseSensitive.put("gen", "Gen");
    palabrasReservadasCaseSensitive.put("eje", "Eje");
    palabrasReservadasCaseSensitive.put("capivara", "Capivara");
    
    if (esPalabraReservadaIncorrecta(primerToken, palabrasReservadasCaseSensitive)) {
        String palabraCorrecta = palabrasReservadasCaseSensitive.get(primerToken.toLowerCase());
        String errorMsg = "La palabra reservada '" + primerToken + "' debe empezar con mayúscula. Escriba '" + palabraCorrecta + "' en lugar de '" + primerToken + "'";
        errores.add(numeroLinea + "|" + primerToken + "|" + errorMsg);
        resultado.append("Línea " + numeroLinea + ": " + errorMsg + "\n");
    } else if (Arrays.asList("Vill", "Con", "Nad", "Gen").contains(primerToken)) {
        analizarDeclaracionVariable(tokens, numeroLinea, errores, variablesDeclaradas, resultado);
    } else if (linea.contains("=")) {
        analizarAsignacion(linea, numeroLinea, errores, variablesDeclaradas, resultado);
    } else if (primerToken.equals("Eje")) {
        analizarLlamadaFuncion(tokens, numeroLinea, errores, funcionesDeclaradas, resultado);
    } else if (esEstructuraControl(primerToken)) {
        errores.add(numeroLinea + "|" + linea + "|Estructura de control no soportada. Las estructuras como 'Si', 'Mientras' o 'Para' no están permitidas en esta versión");
        resultado.append("Línea " + numeroLinea + ": Estructura de control no soportada. Las estructuras como 'Si', 'Mientras' o 'Para' no están permitidas en esta versión\n");
    } else if (esDeclaracionFuncion(tokens)) {
        errores.add(numeroLinea + "|" + linea + "|Declaración de función no soportada. Las funciones definidas con 'Hacer' no están permitidas en esta versión");
        resultado.append("Línea " + numeroLinea + ": Declaración de función no soportada. Las funciones definidas con 'Hacer' no están permitidas en esta versión\n");
    } else {
        String errorMsg = "Sentencia no reconocida. Asegúrese de usar una declaración (Vill, Con, Nad, Gen), asignación (X = 5) o llamada a función (Eje ( Capivara ))";
        errores.add(numeroLinea + "|" + linea + "|" + errorMsg);
        resultado.append("Línea " + numeroLinea + ": " + errorMsg + "\n");
    }
}

