private boolean esDeclaracionVariable(String[] tokens) {
    if (tokens.length < 2) return false;
    Set<String> tiposVariable = new HashSet<>(Arrays.asList("Vill", "Con", "Nad", "Gen"));
    return tiposVariable.contains(tokens[0]) && esIdentificadorValido(tokens[1]);
}

private boolean esAsignacion(String linea) {
    return linea.contains("=") && !linea.contains("==");
}

private boolean esLlamadaFuncion(String[] tokens) {
    return tokens.length >= 3 && 
           tokens[0].equals("Eje") && 
           tokens[1].equals("(") && 
           tokens[tokens.length - 1].equals(")");
}

private boolean esEstructuraControl(String token) {
        Set<String> estructuras = new HashSet<>(Arrays.asList("Si", "Mientras", "Para"));
        return estructuras.contains(token);
    }

    private boolean esDeclaracionFuncion(String[] tokens) {
        return tokens.length >= 4 && 
               tokens[0].equals("Hacer") && 
               esIdentificadorNuevo(tokens[1]) &&
               tokens[2].equals("(");
    }

private boolean esIdentificadorValido(String token) {
    return token != null && 
           Character.isUpperCase(token.charAt(0)) && 
           token.matches("[A-Z][A-Za-z0-9]*");
}

