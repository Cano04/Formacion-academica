    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        DefaultTableModel modelo = (DefaultTableModel) Descripcion_Table.getModel();
        while (modelo.getRowCount() > 0) {
            modelo.removeRow(0);
        }
        try {
            String Producto= Buscar_Field.getText();
            DefaultTableModel Tabla=(DefaultTableModel) Descripcion_Table.getModel();
            datos Obj_Datos= new datos();
            Obj_Datos.conectar();
            String sql="select * from olimpo where NVenta='"+Producto+"';";
            ResultSet conjreg=Obj_Datos.obtenerDatos(sql);
            while(conjreg.next())
            {
                NVenta=conjreg.getString(1);
                Nombre=conjreg.getString(2);
                Cantidad= conjreg.getString(3);
                Monto_Total= conjreg.getString(4);
                Fecha=conjreg.getString(5);
                String[] Fila={NVenta, Nombre, Cantidad, Monto_Total, Fecha};
                Tabla.addRow(Fila);
            }
        } catch (SQLException ex) {
            Logger.getLogger(Accesorios.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

