    private void Buscar_ButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Buscar_ButtonActionPerformed
        DefaultTableModel modelo = (DefaultTableModel) Descripcion_Table.getModel();
        while (modelo.getRowCount() > 0) {
            modelo.removeRow(0);
        }
        try {
        String Refaccion= Busqueda_Field.getText();
        DefaultTableModel Tabla=(DefaultTableModel) Descripcion_Table.getModel();
        datos Obj_Datos= new datos();
        Obj_Datos.conectar();
        String sql="select * from refacciones where Nombre='"+Refaccion+"';";
        ResultSet conjreg=Obj_Datos.obtenerDatos(sql);
        while(conjreg.next())
        {
            ID=conjreg.getString(1);
            Nombre=conjreg.getString(2);
            Cantidad=conjreg.getString(3);
            String[] Fila={ID, Nombre, Cantidad,};
       Tabla.addRow(Fila);
        }
        } catch (SQLException ex) {
            Logger.getLogger(Accesorios.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_Buscar_ButtonActionPerformed


