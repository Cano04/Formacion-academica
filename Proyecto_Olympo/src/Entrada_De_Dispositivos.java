    private void Telefono_FieldKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_Telefono_FieldKeyTyped
    int key = evt.getKeyChar();
    boolean numero= key>=48 && key<=57;
    if(!numero)
    {
        evt.consume();
    }
    if(Telefono_Field.getText().length() >=10)
    {
        evt.consume();
    }
    
    }//GEN-LAST:event_Telefono_FieldKeyTyped

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if(Marca_Field.getText().equals("") || Modelo_Field.getText().equals("") || Telefono_Field.getText().equals("") || Estado_Field.getText().equals("")
        || Nombre_Cliente_Field.getText().equals(""))
        {
             JOptionPane.showMessageDialog(null,"Ingresa datos");
        }
        else if(Telefono_Field.getText().length() <10)
        {
            JOptionPane.showMessageDialog(null,"Ingresa numero de telefono");
        }
        else
        {
            String mes = (String) Mes_Box.getSelectedItem();
            String dia = (String) Dia_Box.getSelectedItem();
            String año = (String) Año_Box.getSelectedItem();
            String Fecha = dia + "-" + mes + "-" + año;
            datos x= new datos();
            try {
                x.conectar();
                String sql="insert into dispositivos values (null,'"+Marca_Field.getText()+"','"+Modelo_Field.getText()+"','"+Telefono_Field.getText()+"','"+Estado_Field.getText()+"','"+Fecha+"','"+Nombre_Cliente_Field.getText()+"');";
                x.actualizar(sql);
            } catch (SQLException ex) {
                Logger.getLogger(Entrada_De_Dispositivos.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

